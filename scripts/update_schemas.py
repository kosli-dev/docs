"""Generate the static JSON Schema files from their sources of truth.

The schemas published as static assets from this repo are generated by the
`kosli-dev/server` API from its Pydantic models, and the OPA capabilities file
by `kosli-dev/opa-lambda` from the capability set the evaluator compiles
against. Editing the committed copies by hand lets them drift from what is
actually enforced, so this script fetches them and writes them to the
published paths.

| Published file                          | Source                                               |
|-----------------------------------------|------------------------------------------------------|
| schemas/flow-template/v1.json           | GET /api/v2/schemas/flow-template/v1                 |
| schemas/policy/v1.json                  | GET /api/v2/schemas/environment-policy/v1            |
| schemas/evaluation-input/trail/v1.json  | GET /api/v2/schemas/evaluation-input/trail/v1        |
| schemas/evaluation-input/trails/v1.json | GET /api/v2/schemas/evaluation-input/trails/v1       |
| rego/capabilities/v1.json               | capabilities.json at opa-lambda's latest release tag |

opa-lambda is private, so the capabilities file needs
OPA_LAMBDA_CROSS_REPO_READ_TOKEN, a token that can read its contents. The
release tag, not main, is what production runs.

Usage:
    python scripts/update_schemas.py            # regenerate the files in place
    python scripts/update_schemas.py --check     # exit non-zero if they drift
"""
import argparse
import json
import os
import sys
from pathlib import Path

import requests

_API_BASE = "https://app.kosli.com/api/v2/schemas"
_REPO_ROOT = Path(__file__).resolve().parent.parent

# endpoint path (under _API_BASE) -> committed file (relative to repo root)
_SCHEMAS = {
    "flow-template/v1": "schemas/flow-template/v1.json",
    "environment-policy/v1": "schemas/policy/v1.json",
    "evaluation-input/trail/v1": "schemas/evaluation-input/trail/v1.json",
    "evaluation-input/trails/v1": "schemas/evaluation-input/trails/v1.json",
}

_OPA_LAMBDA_API = "https://api.github.com/repos/kosli-dev/opa-lambda"

# file in opa-lambda -> committed file (relative to repo root)
_CAPABILITIES = {
    "capabilities.json": "rego/capabilities/v1.json",
}


def fetch_schema(endpoint):
    """Fetch the schema served at endpoint and return it as a dict."""
    url = f"{_API_BASE}/{endpoint}"
    response = requests.get(url, timeout=30)
    response.raise_for_status()
    return response.json()


def _opa_lambda_get(path, accept="application/vnd.github+json", **kwargs):
    token = os.environ.get("OPA_LAMBDA_CROSS_REPO_READ_TOKEN")
    if not token:
        sys.exit("OPA_LAMBDA_CROSS_REPO_READ_TOKEN is not set: it is needed to read the private kosli-dev/opa-lambda repo.")
    response = requests.get(
        f"{_OPA_LAMBDA_API}/{path}",
        headers={"Authorization": f"Bearer {token}", "Accept": accept},
        timeout=30,
        **kwargs,
    )
    response.raise_for_status()
    return response


def latest_release_tag():
    """Return opa-lambda's newest release-<timestamp> tag, the one production runs."""
    refs = _opa_lambda_get("git/matching-refs/tags/release-").json()
    if not refs:
        sys.exit("kosli-dev/opa-lambda has no release-* tag.")
    # The timestamp is zero-padded, so the newest tag sorts last.
    return max(ref["ref"].removeprefix("refs/tags/") for ref in refs)


def fetch_capabilities(path):
    """Fetch path from opa-lambda at its latest release tag and return it as a dict."""
    tag = latest_release_tag()
    try:
        response = _opa_lambda_get(
            f"contents/{path}", accept="application/vnd.github.raw+json", params={"ref": tag}
        )
    except requests.HTTPError as error:
        if error.response is not None and error.response.status_code == 404:
            sys.exit(f"{path} is not in kosli-dev/opa-lambda at {tag}: deploy a release that has it.")
        raise
    return response.json()


def _sources():
    """Yield (committed file, where it comes from, fetch) for every published file."""
    for endpoint, rel_path in _SCHEMAS.items():
        yield rel_path, f"{_API_BASE}/{endpoint}", lambda endpoint=endpoint: fetch_schema(endpoint)
    for path, rel_path in _CAPABILITIES.items():
        yield rel_path, f"kosli-dev/opa-lambda:{path}", lambda path=path: fetch_capabilities(path)


def render(schema):
    """Return schema as a deterministic, pretty-printed JSON string with a trailing newline."""
    return json.dumps(schema, indent=2, ensure_ascii=False) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Do not write; exit 1 if any committed file differs from its source.",
    )
    args = parser.parse_args()

    drifted = []
    for rel_path, source, fetch in _sources():
        target = _REPO_ROOT / rel_path
        generated = render(fetch())

        if args.check:
            current = target.read_text(encoding="utf-8") if target.exists() else None
            if current != generated:
                drifted.append(rel_path)
                print(f"drift: {rel_path} differs from {source}")
            else:
                print(f"ok:    {rel_path}")
            continue

        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(generated, encoding="utf-8")
        print(f"wrote: {rel_path} (from {source})")

    if args.check and drifted:
        print(
            f"\n{len(drifted)} schema file(s) are out of date. "
            "Run `python scripts/update_schemas.py` to regenerate.",
            file=sys.stderr,
        )
        sys.exit(1)


if __name__ == "__main__":
    main()
